import assert from 'node:assert/strict';
import { serverGame as game } from './dist/server/index.js';
import { controllerGame } from './dist/controller/index.js';
const context = { now: 1000, language: 'de', players: [{id:'a', name:'Anna'}, {id:'b',name:'Ben'}], roundNumber:1 };
const state = game.startRound(game.createInitialState(context), context);
const actor = state.actorPlayerId;
const other = actor === 'a' ? 'b' : 'a';
const input = {type:'pantomime_guessed', playerId:actor, sentAt:2000};
assert.equal(game.toPublicState(state, context).secretTerm, undefined);
assert.equal(game.toControllerStateForPlayer(state, context, other).secretTerm, undefined);
assert.equal(game.toControllerStateForPlayer(state, context, actor).secretTerm, state.secretTerm);
assert.equal(game.handleInput(state, {...input,playerId:other}, {...context,now:2000}), state);
assert.deepEqual(game.buildScore(state), []);
const guessed = game.handleInput(state,input,{...context,now:2000});
assert.equal(guessed.revealedTerm,state.secretTerm);
assert.equal(guessed.phase,'playing');
assert.equal(guessed.finishAt,state.finishAt);
assert.equal(game.tick(guessed,100,{...context,now:3000}),guessed);
assert.equal(game.handleInput(guessed,input,{...context,now:3000}),guessed);
assert.equal(game.buildScore(guessed)[0].delta,1);
assert.equal(game.handleInput(state,input,{...context,now:state.finishAt}),state);
assert.equal(game.tick(guessed,100,{...context,now:state.finishAt}).phase,'locked');
assert.ok(!game.tick(state,100,{...context,now:state.finishAt}).message.includes(state.secretTerm));
let submitted;
const layout = controllerGame.buildLayout({state:{player:{id:actor},game:{phase:'playing',state:{...state,finishAt:Date.now()+60000}}},onInput:x=>submitted=x});
layout.choices[0].onSelect();
assert.equal(submitted.type,'pantomime_guessed');
assert.equal(submitted.playerId,actor);
const next=game.startRound(guessed,{...context,now:100000});
assert.equal(next.revealedTerm,undefined);
assert.equal(next.guessedAt,undefined);
console.log('PASS: privacy, actor authorization, reveal, continuing deadline, duplicate/late rejection, scoring, timeout, controller action, round reset');
